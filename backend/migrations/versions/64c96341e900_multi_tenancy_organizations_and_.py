def _backfill(bind) -> None:
    """Give every user a personal organization and attribute their rows to it."""
    import uuid
    from datetime import datetime

    users = bind.execute(sa.text(
        "SELECT id, email, name, plan FROM users"
    )).fetchall()

    now = datetime.utcnow()
    for user_id, email, name, plan in users:
        org_id = uuid.uuid4().hex
        if name:
            org_name = f"{name}'s workspace"
        else:
            local = (email or "account").split("@")[0]
            org_name = f"{local}'s workspace"

        bind.execute(
            sa.text(
                "INSERT INTO organizations "
                "(id, name, is_personal, plan, created_at) "
                "VALUES (:id, :name, :is_personal, :plan, :created_at)"
            ),
            {
                "id": org_id,
                "name": org_name,
                "is_personal": True,
                # Carry the old plan across. Defaulting to 'free' here would
                # quietly cancel every paying customer.
                "plan": plan or "free",
                "created_at": now,
            },
        )
        bind.execute(
            sa.text(
                "INSERT INTO organization_memberships "
                "(id, organization_id, user_id, role, created_at) "
                "VALUES (:id, :org, :user, :role, :created_at)"
            ),
            {
                "id": uuid.uuid4().hex,
                "org": org_id,
                "user": user_id,
                "role": "owner",
                "created_at": now,
            },
        )
        for table in TENANT_TABLES:
            bind.execute(
                sa.text(
                    f"UPDATE {table} SET organization_id = :org WHERE user_id = :user"
                ),
                {"org": org_id, "user": user_id},
            )

    # Any tenant row whose user has vanished cannot be attributed. There should
    # be none (every tenant table has a NOT NULL FK to users), but a row left
    # behind would block the NOT NULL tightening below with a confusing error,
    # so fail loudly here instead.
    for table in TENANT_TABLES:
        orphans = bind.execute(sa.text(
            f"SELECT COUNT(*) FROM {table} WHERE organization_id IS NULL"
        )).scalar()
        if orphans:
            raise RuntimeError(
                f"{orphans} row(s) in {table} could not be attributed to an "
                "organization. Inspect them before re-running this migration."
            )


