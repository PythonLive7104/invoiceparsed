"""multi-tenancy: organizations and memberships

Introduces the tenant boundary. Every tenant-owned row gains an
`organization_id`, and the plan moves from `users.plan` to
`organizations.plan` because a team shares one monthly allowance.

Existing accounts keep working untouched: each gets a personal organization
with itself as owner, carrying over whatever plan the user was on, and all of
its rows are attributed to that organization. A solo account therefore becomes
an organization of one and behaves exactly as before.

ORDER MATTERS here, and the autogenerated version got it wrong in two ways
that would each have broken a real deploy:

  1. It added `organization_id` as NOT NULL with no default, which fails
     immediately on any table that already has rows. The columns are added
     nullable, backfilled, and only then made NOT NULL.
  2. It dropped `users.plan` in the same breath as creating
     `organizations.plan`. The old value has to be READ first, or every paying
     customer silently lands on Free.

The NOT NULL tightening is done with batch_alter_table so it works on SQLite
(which cannot ALTER a column in place) as well as Postgres.
"""
