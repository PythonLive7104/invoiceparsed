"""approval workflows (P2.5)

Six tables, all new. Nothing existing is altered, so there is no ADD COLUMN
here to get wrong and the downgrade is a clean drop.

The split between `approval_rules` / `approval_rule_steps` (configuration) and
`approval_requests` / `approval_request_steps` (instances) is the point of the
design rather than normalization for its own sake. A request's steps are
MATERIALIZED from the rule at submission and never re-read from it, so editing
a rule cannot rewrite an approval somebody is partway through signing. The
people who signed a chain signed a specific chain, and an audit trail that
changes shape retrospectively is not an audit trail.

`approval_events` is append-only and is the only place some things are
recorded at all - a reminder sent, a question asked, an answer given - none of
which leave a trace in the steps.

`approval_delegations` is date-bounded by design: an open-ended delegation is
how one person quietly acquires everybody's authority long after the holiday
it was created for.

Amounts are Numeric, never Float, because rule thresholds are compared against
order and invoice totals that are themselves Numeric - a Float bound would
disagree with the figures it is gating by exactly the amounts this product
exists to catch.
"""
